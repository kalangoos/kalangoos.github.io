// Writes src/styles/tokens.css from design/tokens/tokens.json (the variables exported from the
// FigCraft Design System): colours in both modes, radii and spacing. Run with `npm run tokens`.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
// the Design System's tokens: a copy in this repository (design-tokens/), or the monorepo's design/tokens/
const tokensFile = () => [join(here, '../design-tokens/tokens.json'), join(here, '../../design/tokens/tokens.json')].find((p) => existsSync(p));
const all = JSON.parse(readFileSync(tokensFile(), 'utf8'));
const colors = all['KalangoOS · Cores'];
const layout = all['KalangoOS · Layout'];

const css = (s) => s.replace('cor/', '').replace(/_/g, '-');
const block = (mode) =>
  Object.entries(colors)
    .filter(([k]) => k.startsWith('cor/'))
    .map(([k, v]) => `  --${css(k)}: ${v[mode]};`)
    .join('\n');

const fonts = {
  Escuro: `  --font-ui: "Inter", system-ui, sans-serif;\n  --font-display: "URW Gothic", "Jost", "Inter", system-ui, sans-serif;\n  --display-weight: 600;`,
  Claro: `  --font-ui: "Roboto", system-ui, sans-serif;\n  --font-display: "Ubuntu", "Roboto", system-ui, sans-serif;\n  --display-weight: 700;`,
};

const radius = Object.entries(layout)
  .filter(([k]) => k.startsWith('raio/'))
  .map(([k, v]) => `  --radius-${k.slice(5)}: ${v['Padrão'] === 999 ? '999px' : v['Padrão'] + 'px'};`)
  .join('\n');
const space = Object.entries(layout)
  .filter(([k]) => k.startsWith('espaco/'))
  .map(([k, v]) => `  --space-${k.slice(7)}: ${v['Padrão']}px;`)
  .join('\n');

const out = `/* Generated by scripts/gen-tokens.mjs from design/tokens/tokens.json — do not edit by hand. */
/* Dark ("Escuro") is the default, as in the system; light ("Claro") follows prefers-color-scheme or the toggle. */
:root {
  color-scheme: dark;
${block('Escuro')}
${fonts.Escuro}
${radius}
${space}
  --bar-height: ${layout['barra/altura']['Padrão']}px;
  --dock-icon: ${layout['dock/icone']['Padrão']}px;
  --font-mono: "JetBrains Mono", ui-monospace, monospace;
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme="dark"]) {
    color-scheme: light;
${block('Claro').replace(/^/gm, '  ')}
${fonts.Claro.replace(/^/gm, '  ')}
  }
}
:root[data-theme="light"] {
  color-scheme: light;
${block('Claro')}
${fonts.Claro}
}
`;
writeFileSync(join(here, '../src/styles/tokens.css'), out);
console.log('tokens.css written');
