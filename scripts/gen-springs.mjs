// Writes src/styles/motion.css: the Design System's springs (design/tokens/tokens.json,
// "KalangoOS · Motion") as CSS linear() easings with their settle times.
// Run with `npm run springs` after the tokens change.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
// the Design System's tokens: a copy in this repository (design-tokens/), or the monorepo's design/tokens/
const tokensFile = () => [join(here, '../design-tokens/tokens.json'), join(here, '../../design/tokens/tokens.json')].find((p) => existsSync(p));
const tokens = JSON.parse(readFileSync(tokensFile(), 'utf8'))['KalangoOS · Motion'];
const v = (name) => tokens[name]['Padrão'];

const springs = {
  suave: 'mola/suave',
  rapida: 'mola/rápida',
  elastica: 'mola/elástica',
  lenta: 'mola/lenta',
};

// Position of a damped spring going from 0 to 1 at rest, mass m, stiffness k, damping c.
function position(t, m, k, c) {
  const w0 = Math.sqrt(k / m);
  const zeta = c / (2 * Math.sqrt(k * m));
  if (zeta < 1) {
    const wd = w0 * Math.sqrt(1 - zeta * zeta);
    return 1 - Math.exp(-zeta * w0 * t) * (Math.cos(wd * t) + ((zeta * w0) / wd) * Math.sin(wd * t));
  }
  if (zeta === 1) return 1 - Math.exp(-w0 * t) * (1 + w0 * t);
  const wd = w0 * Math.sqrt(zeta * zeta - 1);
  return 1 - Math.exp(-zeta * w0 * t) * (Math.cosh(wd * t) + ((zeta * w0) / wd) * Math.sinh(wd * t));
}

function settle(m, k, c) {
  // first time after which the spring stays within 0.1% of rest
  const dt = 1 / 1000;
  let last = 0;
  for (let t = 0; t < 3; t += dt) {
    if (Math.abs(1 - position(t, m, k, c)) > 0.001) last = t;
  }
  return Math.ceil((last + dt) * 1000);
}

const lines = [
  '/* Generated by scripts/gen-springs.mjs from design/tokens/tokens.json — do not edit by hand. */',
  '/* The Design System springs as CSS linear() easings; each --spring-*-ms is the time it takes to settle. */',
  ':root {',
];
for (const [id, base] of Object.entries(springs)) {
  const m = v(`${base}/massa`), k = v(`${base}/rigidez`), c = v(`${base}/amortecimento`);
  const ms = settle(m, k, c);
  const n = 48;
  const pts = [];
  for (let i = 0; i <= n; i++) {
    const t = (i / n) * (ms / 1000);
    const x = i === n ? 1 : position(t, m, k, c);
    pts.push(+x.toFixed(4));
  }
  lines.push(`  /* ${base}: massa ${m}, rigidez ${k}, amortecimento ${c} */`);
  lines.push(`  --spring-${id}: linear(${pts.join(', ')});`);
  lines.push(`  --spring-${id}-ms: ${ms}ms;`);
}
for (const name of ['instant', 'fast', 'hover', 'base', 'panel', 'window', 'page']) {
  lines.push(`  --motion-${name}: ${v(`motion/${name}`)}ms;`);
}
lines.push(`  --cascade-ms: ${v('coreografia/cascata_ms')}ms;`);
lines.push(`  --cascade-max: ${v('coreografia/max_itens')};`);
lines.push(`  --reduced-ms: ${v('coreografia/reduzido_ms')}ms;`);
lines.push('}');
writeFileSync(join(here, '../src/styles/motion.css'), lines.join('\n') + '\n');
console.log('motion.css written');
